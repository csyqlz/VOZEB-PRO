export type HelpArticleId = (typeof helpArticles)[number]["id"];

export function findHelpArticle(id: string | null | undefined) {
    return helpArticles.find((article) => article.id === id);
}

export function searchHelpArticles(query: string) {
    const normalized = query.trim().toLocaleLowerCase("zh-CN");
    if (!normalized) return helpArticles;
    return helpArticles.filter((article) => articleSearchText(article).includes(normalized));
}

function articleSearchText(article: HelpArticle) {
    return [
        article.label,
        article.title,
        article.summary,
        ...article.keywords,
        ...article.outcomes,
        ...article.flow.flatMap((step) => [step.title, step.detail]),
        ...article.steps.flatMap((step) => [step.title, step.description, ...step.checklist, step.tip || ""]),
        ...article.faqs.flatMap((faq) => [faq.question, faq.answer]),
    ]
        .join(" ")
        .toLocaleLowerCase("zh-CN");
}
